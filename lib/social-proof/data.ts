export type NotificationData = {
  name: string;
  city: string;
  action: string;
  time: string;
};

function pick<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)] as T;
}

export function generateNotification(last: NotificationData | null): NotificationData {
  let name: string;
  let city: string;

  // Avoid repeating same name or city as previous
  do { name = pick(FEMALE_NAMES); } while (name === last?.name);
  do { city = pick(RUSSIAN_CITIES); } while (city === last?.city);

  return { name, city, action: pick(ACTIONS), time: pick(TIMES) };
}

export function randomDelay(minMs: number, maxMs: number): number {
  return Math.floor(Math.random() * (maxMs - minMs + 1)) + minMs;
}
